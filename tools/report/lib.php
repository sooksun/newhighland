function q(PDO $pdo, string $sql, array $p = []): array
{
    $st = $pdo->prepare($sql); $st->execute($p); return $st->fetchAll();
}
function q1(PDO $pdo, string $sql, array $p = []): ?array
{
    $r = q($pdo, $sql, $p); return $r[0] ?? null;
}

