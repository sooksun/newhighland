/** histogram bins ของคะแนน 0-100 ทีละ 10 */
function scoreBins(array $scores): array
{
    $bins = [];
    for ($i = 0; $i < 100; $i += 10) $bins[$i . '–' . ($i + 9)] = 0;
    $bins['100'] = 0;
    foreach ($scores as $s) {
        if ($s === null) continue;
        if ($s >= 100) { $bins['100']++; continue; }
        $lo = (int) (floor($s / 10) * 10);
        $bins[$lo . '–' . ($lo + 9)]++;
    }
    return $bins;
}
