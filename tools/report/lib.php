function num($v): ?float
{
    if ($v === null || $v === '' ) return null;
    return is_numeric($v) ? (float) $v : null;
}
function pct(float $part, float $whole, int $dp = 1): string
{
    return $whole > 0 ? number_format($part / $whole * 100, $dp) . '%' : '–';
}
function pctf(float $part, float $whole): float
{
    return $whole > 0 ? $part / $whole * 100 : 0.0;
}
function nf($v, int $dp = 0): string
{
    if ($v === null || $v === '') return '–';
    return number_format((float) $v, $dp);
}
function h(?string $s): string
{
    return htmlspecialchars((string) $s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/** สถิติเชิงพรรณนา (SD กลุ่มตัวอย่าง ddof=1, percentile linear interpolation — ตรงกับ pandas) */
function describe(array $vals): array
{
    $vals = array_values(array_filter($vals, fn($v) => $v !== null));
    $n = count($vals);
    if ($n === 0) return ['n'=>0,'mean'=>null,'sd'=>null,'min'=>null,'q1'=>null,'median'=>null,'q3'=>null,'max'=>null,'sum'=>0.0];
    sort($vals, SORT_NUMERIC);
    $sum  = array_sum($vals);
    $mean = $sum / $n;
    $sd = 0.0;
    if ($n > 1) { $ss = 0.0; foreach ($vals as $x) $ss += ($x - $mean) ** 2; $sd = sqrt($ss / ($n - 1)); }
    return [
        'n'=>$n, 'sum'=>$sum,
        'mean'=>round($mean,2), 'sd'=>round($sd,2),
        'min'=>round($vals[0],2), 'q1'=>round(percentile($vals,0.25),2),
        'median'=>round(percentile($vals,0.50),2), 'q3'=>round(percentile($vals,0.75),2),
        'max'=>round($vals[$n-1],2),
    ];
}
function percentile(array $sorted, float $p): float
{
    $n = count($sorted);
    if ($n === 0) return 0.0;
    if ($n === 1) return (float) $sorted[0];
    $rank = $p * ($n - 1);
    $lo = (int) floor($rank); $hi = (int) ceil($rank);
    if ($lo === $hi) return (float) $sorted[$lo];
    return $sorted[$lo] + ($sorted[$hi] - $sorted[$lo]) * ($rank - $lo);
}
/** Pearson r */
function pearson(array $x, array $y): float
{
    $n = count($x);
    if ($n < 2) return 0.0;
    $sx=array_sum($x); $sy=array_sum($y); $sxx=0.0; $syy=0.0; $sxy=0.0;
    for ($i=0;$i<$n;$i++){ $sxx+=$x[$i]*$x[$i]; $syy+=$y[$i]*$y[$i]; $sxy+=$x[$i]*$y[$i]; }
    $num = $n*$sxy - $sx*$sy;
    $den = sqrt(($n*$sxx-$sx*$sx)*($n*$syy-$sy*$sy));
    return $den > 0 ? $num/$den : 0.0;
}
function corrStrength(float $r): string
{
    $a = abs($r);
    if ($a >= 0.7) return 'สูงมาก';
    if ($a >= 0.5) return 'สูง';
    if ($a >= 0.3) return 'ปานกลาง';
    if ($a >= 0.1) return 'ต่ำ';
    return 'แทบไม่มี';
}
